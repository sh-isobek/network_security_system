def translate_html(html: str, language: str) -> str:
    """Translate rendered HTML without changing routes or form field keys."""
    if language != "ru":
        return html
    for source in sorted(RU_TRANSLATIONS, key=len, reverse=True):
        html = html.replace(source, RU_TRANSLATIONS[source])
    return html.replace('<html lang="uz">', '<html lang="ru">')
